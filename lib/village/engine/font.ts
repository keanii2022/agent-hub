const MISSING_GLYPH_ROWS = "##### #...# #...# #...# #...# #...# #####";

function glyphFromRows(character: string, rowsText: string): Glyph {
  const rows = rowsText.split(" ");
  const blankRow = GLYPH_BLANK.repeat(GLYPH_WIDTH);
  if (rows.length > GLYPH_HEIGHT) {
    throw new Error(`The glyph for "${character}" has more than ${GLYPH_HEIGHT} rows`);
  }
  for (const row of rows) {
    const onlyInkAndBlank = [...row].every((mark) => mark === GLYPH_INK || mark === GLYPH_BLANK);
    if (row.length !== GLYPH_WIDTH || !onlyInkAndBlank) {
      throw new Error(`The glyph for "${character}" has a bad row: "${row}"`);
    }
  }
  return [...rows, ...Array<string>(GLYPH_HEIGHT - rows.length).fill(blankRow)];
}

const glyphs = new Map<string, Glyph>(
  Object.entries(glyphRows).map(([character, rowsText]) => [
    character,
    glyphFromRows(character, rowsText),
  ]),
);

export const missingGlyph: Glyph = glyphFromRows("missing", MISSING_GLYPH_ROWS);

export function hasGlyph(character: string): boolean {
  return glyphs.has(character);
}

/** A character the font does not know comes back as a hollow box, so a gap in the font shows on screen. */
export function glyphFor(character: string): Glyph {
  return glyphs.get(character) ?? missingGlyph;
}

export function measureText(text: string): { width: number; height: number } {
  const lines = text.split("\n");
  const longestLine = Math.max(...lines.map((line) => [...line].length));
  return {
    width: longestLine === 0 ? 0 : longestLine * (GLYPH_WIDTH + LETTER_GAP) - LETTER_GAP,
    height: (lines.length - 1) * LINE_HEIGHT + GLYPH_HEIGHT,
  };
}
